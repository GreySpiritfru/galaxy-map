/* ============================================================
   Краткая подсказка по управлению картой. Сама по себе НЕ открывается —
   только по клику на кнопку "?" в углу карты. Для новых игроков (кто ещё
   ни разу не нажимал — флаг в localStorage, живёт в браузере конкретного
   игрока, к сайту/репозиторию отношения не имеет) кнопка мягко пульсирует,
   чтобы её было видно, но не мигает резко и не лезет с окном сама.
   ============================================================ */
import { openModal } from './modal.js?v=60';

const ONBOARDING_SEEN_KEY = 'galaxyMapOnboardingSeen';
const helpBtn = document.getElementById('helpBtn');

function showOnboarding() {
  openModal(`
    <div class="modal-title">Как пользоваться картой</div>
    <div>
      Перетаскивание — пальцем или мышью, масштаб — щипком или колёсиком.<br><br>
      Тапни по названию системы — откроется её подробная карта (если уже готова).<br><br>
      Тапни по цветной точке/иконке на карте — покажется карточка с описанием фракции или персонажа.<br><br>
      Кнопка 🚀 «Феном» — открывает подробную карту корабля-города.<br><br>
      Кнопка 📖 «Справочник» — статьи о галактике, расах, магии и технологиях; между ними можно переключаться прямо внутри статьи.<br><br>
      Кнопка «⋯» — зум +/－, сброс вида, режим калибровки координат.<br><br>
      Открыть эту подсказку снова можно кнопкой «?» в углу карты.
    </div>
  `);
}

helpBtn.addEventListener('click', () => {
  showOnboarding();
  helpBtn.classList.remove('pulse');
  try { localStorage.setItem(ONBOARDING_SEEN_KEY, '1'); } catch (e) {}
});

// Если ещё ни разу не нажимали — просто подсвечиваем кнопку пульсацией,
// само окно не трогаем. Недоступен localStorage (приватный режим и т.п.) —
// тоже не страшно, кнопка просто останется обычной, без пульсации.
try {
  if (!localStorage.getItem(ONBOARDING_SEEN_KEY)) {
    helpBtn.classList.add('pulse');
  }
} catch (e) {}
