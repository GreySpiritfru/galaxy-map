helpBtn.addEventListener('click', () => {
  showOnboarding();
  helpBtn.classList.remove('pulse');
  try { localStorage.setItem(ONBOARDING_SEEN_KEY, '1'); } catch (e) {}
});

// Если ещё ни разу не нажимали — просто подсвечиваем кнопку пульсацией,
// само окно не трогаем. Недоступен localStorage (приватный режим и т.п.) —
// тоже не страшно, кнопка просто останется обычной, без пульсации.
try {
  if (!localStorage.getItem(ONBOARDING_SEEN_KEY)) {
    helpBtn.classList.add('pulse');
  }
} catch (e) {}
