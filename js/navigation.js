/* ============================================================
   Единый "шаг назад" — общая точка выхода для трёх независимых триггеров:
   ESC на компьютере, кнопка BackButton в шапке Telegram Mini App (и на
   телефоне, и в Telegram Desktop), History API обычного браузера вне
   Telegram (кнопка/жест "назад", включая мобильный свайп с края экрана) —
   и (13.09.2026) видимой ✕/↩-кнопки в каждом тулбаре, которая теперь тоже
   вызывает эту же функцию, а не свою собственную логику в каждом модуле.

   ⚠️ Жест/аппаратная кнопка "назад" ВНУТРИ самого Telegram (Android — общий
   свайп, iOS — свайп с края) до страницы вообще не долетают и ничего тут не
   триггерят — Telegram резервирует их под сворачивание/закрытие всего
   мини-приложения, это подтверждено официальным issue в репозитории
   Telegram-iOS (открыт с 2023, до сих пор без ответа). Единственный хук
   ВНУТРИ Telegram — именно кнопка BackButton (стрелка в шапке), поэтому она
   показывается/прячется по факту вручную, а не пробрасывается откуда-то
   ещё. Вне Telegram (обычная ссылка в браузере) это не проблема — там
   работает обычный History API, включая мобильный жест.

   Глубина вложенности (13.09.2026) — НЕ фиксированный потолок в 2 уровня, а
   счётчик того, сколько независимых слоёв сейчас реально открыто разом:
   модал (карточка маркера/статья-справочник/окно персонажа — все три через
   один #modalBackdrop), сюжет (.story-overlay) и локация (.phenom-overlay,
   она же "Феном") могут быть открыты ОДНОВРЕМЕННО, если сюжет привязан к
   локации и был открыт вкладкой ИЗ её окна (см. setPhenomChildren в
   js/phenom.js) — тогда это 2 слоя, а персонаж, открытый чипом ИЗ этого
   сюжета, поверх них — уже 3. Система (.system-overlay) — отдельный,
   несвязанный с графом slot (не участвует в этом стекинге, см. isSystemOpen
   ниже и её собственное исключение из общего ✕↔↩-морфинга).

   Раз глубина — не фиксированный масштаб 0..2, а РЕАЛЬНЫЙ подсчёт открытых
   слоёв, "шаг назад" естественно обобщается на произвольную вложенность:
   закрыть самый верхний слой (та же функция, что и у его собственного
   крестика/тапа по фону) — этого достаточно, чтобы закрыть анкету
   персонажа и вернуться в сюжет позади неё, закрыть сюжет и вернуться в
   локацию (Феном) позади него, или закрыть локацию/сюжет и вернуться на
   карту. Полноценного стека КОНКРЕТНЫХ экранов ("вернуться туда же, откуда
   пришёл") всё ещё сознательно нет — см. обсуждение в истории сессии:
   вложенность считается по ТИПАМ слоёв (модал/сюжет/локация/система), а не
   по конкретным id узлов, этого достаточно для всех текущих сценариев.
   ============================================================ */
import { closeModal, isArticleOpen } from './modal.js?v=164';
import { closeSystem, isSystemOpen, isSystemLoreOpen, showSystemMap } from './system-view.js?v=164';
import { closePhenom, isPhenomOpen } from './phenom.js?v=164';
import { closeStory, isStoryOpen } from './stories.js?v=164';
import { closeCharacter, isCharacterOpen } from './characters.js?v=164';
import { closeTour, isTourOpen } from './tour.js?v=164';

function depth() {
  let d = 0;
  // Обучение (js/tour.js, v=155) — самый верхний слой: «назад» и Esc
  // закрывают сначала его, а не окно, которое тур открыл под собой.
  if (isTourOpen()) d++;
  if (isPhenomOpen()) d++;
  /* Своя карта точки (Феном) — ВКЛАДКА того же окна, а не уровень: ✕ на ней
     закрывает окно, как на «Статье» (игрок, 24.09.2026: «панель одна и та
     же, возврат тут не нужен»). Так же устроены вкладки окна системы. В v=134
     карта считалась отдельным уровнем и ✕ превращался в ↩. */
  if (isStoryOpen()) d++;
  // Персонаж с 24.09.2026 — третий слой окна точки (#charOverlay), а не модал.
  if (isCharacterOpen()) d++;
  if (isSystemOpen()) d++;
  if (isArticleOpen()) d++;
  return d;
}

/* Закрывает ровно один верхний слой. Порядок — по фактическому z-index
   (см. грабли №7 и .story-overlay { z-index: 251 } в css/styles.css):
   модал (300) выше сюжета (251), сюжет выше локации/Фенома (250). Система
   (200) — отдельный случай: она не стекуется с сюжетом/локацией (это два
   независимых входа с самой карты галактики), но её ЛОР-статья тоже идёт
   через тот же #modalBackdrop — поэтому проверяем её ПЕРВОЙ и целиком
   делегируем её же собственной логике (showSystemMap/closeSystem), а не
   голому closeModal(): у системы двух вкладок есть свой class-based
   "активный таб", который обновляет только showSystemMap(), и просто
   закрыть модал в обход неё оставило бы "Контролирующую расу" подсвеченной
   поверх уже закрытой статьи. */
/* ⚠️ С 17.09.2026 поверх системы открывается и окно сюжета (вкладка/маркер
   внутри системы), поэтому система больше не проверяется первой — только её
   статья расы (isSystemLoreOpen), а сама система закрывается последней, как
   самый нижний слой. */
function closeTop() {
  if (isTourOpen()) { closeTour(); return; }
  if (isArticleOpen()) { if (isSystemLoreOpen()) showSystemMap(); else closeModal(); return; }
  if (isCharacterOpen()) { closeCharacter(); return; }
  if (isStoryOpen()) { closeStory(); return; }
  if (isPhenomOpen()) { closePhenom(); return; }
  if (isSystemOpen()) { closeSystem(); return; }
}

// --- ESC на компьютере (в т.ч. Telegram Desktop — это обычная веб-страница) ---
document.addEventListener('keydown', (e) => {
  if (e.key === 'Escape' && depth() > 0) closeTop();
});

// --- Telegram Mini App: кнопка BackButton в шапке (Bot API 6.1+) ---
const tg = window.Telegram && window.Telegram.WebApp;
if (tg && tg.BackButton) {
  tg.BackButton.onClick(closeTop);
}

/* --- History API: кнопка/жест "назад" обычного браузера ---
   Три счётчика (не флаги!) разводят ситуации, которые иначе путаются:
   - popstateCloses — сколько записей браузер съел САМ (игрок нажал "назад", мы
     в ответ закрыли слой): эти шаги отматывать ещё раз не нужно;
   - ownTraversals — сколько НАШИХ history.go() ещё не отозвались popstate:
     такой popstate не должен закрывать лишний слой поверх;
   - pushedByUs — сколько записей добавили мы: больше этого числа отматывать
     нельзя ни при каких обстоятельствах, иначе уйдём из приложения наружу.

   ⚠️ Именно счётчики, а не булевы флаги (15.09.2026). Флаг "пришли из
   popstate" умел посчитать ровно один шаг, а sync() отложен до кадра (см.
   ниже) — и если игрок жмёт "назад" быстро или вкладка ушла в фон (там
   requestAnimationFrame тормозится до ~1 раза в секунду!), в один sync()
   схлопывается СРАЗУ НЕСКОЛЬКО popstate. Флаг списывал один шаг, остальные
   код считал "закрытыми крестиком" и честно отматывал ещё раз — то есть
   отматывал вдвое больше, чем нужно. Со счётчиком результат не зависит от
   того, сколько событий попало в одну пачку. */
let popstateCloses = 0;
let ownTraversals = 0;
let pushedByUs = 0;
let lastDepth = 0;

/* Страж: одна лишняя запись в history поверх той, с которой игрок пришёл.

   Зачем (баг, найденный игроком 15.09.2026): "Справочник -> Карта (Феном) ->
   ✕" выкидывало из мини-приложения наружу, на стартовую страницу браузера.
   Корневая причина — в sync() ниже (там же и настоящее исправление), но
   ЛЮБОЙ будущий рассинхрон нашего счётчика с реальной историей браузера
   привёл бы к тому же самому: лишний history.back() — и игрок вылетел из
   карты. Страж делает эту ошибку безобидной: назад уводит на нашу же
   страницу, а не из неё.

   ⚠️ В popstate ниже страж ВОССТАНАВЛИВАЕТСЯ, то есть "назад" из карты не
   выводит вообще никогда (по просьбе игрока). Для Telegram Mini App это
   правильно: приложение закрывается своими средствами Telegram, а не
   браузерной историей. Вне Telegram (обычная ссылка) побочный эффект в том,
   что кнопкой "назад" нельзя уйти на страницу, с которой пришёл — если это
   когда-нибудь окажется неудобным, достаточно убрать re-push в popstate,
   и страж станет одноразовым (гасит один случайный "назад" и пропускает
   следующий). */
history.pushState({guard: true}, '');

window.addEventListener('popstate', () => {
  if (ownTraversals > 0) { ownTraversals--; return; }
  if (depth() > 0) {
    popstateCloses++;
    closeTop();
    return;
  }
  // Открыто ничего нет, а "назад" всё равно пришёл — значит съеден страж
  // (или наш счётчик всё-таки разошёлся). Ставим страж обратно.
  history.pushState({guard: true}, '');
});

/* Кнопки-крестики четырёх тулбаров (не системы, см. её собственное
   исключение выше и в css/styles.css) вешаются СЮДА, а не в своих модулях —
   closeTop() уже знает приоритет между всеми слоями разом, дублировать эту
   логику в articles.js/characters.js/phenom.js/stories.js незачем (было —
   каждый вручную проверял isArticleOpen() перед тем, как закрыть себя). */
['refToolbarClose', 'charToolbarClose', 'phenomClose', 'storyClose'].forEach(id => {
  document.getElementById(id).addEventListener('click', closeTop);
});

/* ✕ превращается в ↩, когда клик по ней реально вернёт к чему-то (глубина
   после клика останется > 0), а не отправит сразу на голую карту — так
   видно разницу между "закрыть совсем" и "подняться на уровень выше" без
   двух отдельных кнопок в ряду (была отдельная .toolbar-back-btn, убрана
   13.09.2026 — с ней ✕ и ↩ ВСЕГДА делали одно и то же, что и подсветил
   игрок: раз показывать ↩ только там, где закрытие не опустошает всё до
   карты, то это ровно то же условие, при котором ✕ и так уже вела бы туда
   же — тождественно морфить одну кнопку вместо второй хуже видимой). */
const morphButtons = ['refToolbarClose', 'charToolbarClose', 'phenomClose', 'storyClose']
  .map(id => document.getElementById(id));

function sync() {
  const d = depth();
  if (tg && tg.BackButton) { d > 0 ? tg.BackButton.show() : tg.BackButton.hide(); }
  const goesBack = d > 1;
  morphButtons.forEach(btn => {
    btn.textContent = goesBack ? '↩' : '✕';
    btn.setAttribute('aria-label', goesBack ? 'Назад' : 'Закрыть');
  });
  /* Глубина может прыгнуть БОЛЬШЕ чем на 1 за один sync() — например, ✕ в
     окне персонажа поверх сюжета поверх локации закрывает всё разом. Раньше
     тут была ровно одна pushState на рост и ровно один history.back() на
     падение, независимо от величины прыжка, — отсюда и разъезжался счёт.
     Теперь записей добавляется/снимается СТОЛЬКО ЖЕ, на сколько изменилась
     глубина, и не больше, чем мы сами когда-то добавили (pushedByUs). */
  if (d > lastDepth) {
    for (let i = lastDepth; i < d; i++) { history.pushState({appDepth: i + 1}, ''); pushedByUs++; }
  } else if (d < lastDepth) {
    let steps = lastDepth - d;
    // Сколько-то из этих шагов браузер уже прошёл сам (игрок нажал "назад",
    // мы закрыли слой в ответ) — их отматывать ещё раз нельзя.
    const already = Math.min(popstateCloses, steps);
    pushedByUs = Math.max(0, pushedByUs - already);
    steps -= already;
    // Остальное закрыли крестиком/фоном/ESC/кнопкой Telegram — подчищаем за
    // собой записи сами, иначе следующий реальный "назад" откатывал бы на
    // состояние, где слой уже и так закрыт (лишние нажатия). Но НЕ больше,
    // чем сами добавили: это последняя преграда между багом и вылетом из
    // приложения наружу.
    steps = Math.min(steps, pushedByUs);
    if (steps > 0) {
      pushedByUs -= steps;
      ownTraversals++;
      history.go(-steps); // один go(-n) = один popstate, сколько бы ни было шагов
    }
  }
  popstateCloses = 0;
  lastDepth = d;
}

/* ⚠️ sync() откладывается до следующего кадра, а не зовётся на каждую
   мутацию (15.09.2026, тот же баг про вылет из приложения).

   Причина: MutationObserver батчит только то, что случилось в ОДНОМ
   микрозадачном чекпоинте. А переходы-замены вида "закрыть статью и открыть
   вместо неё окно локации" (тогда — половинка «Карта» в справочнике, убрана
   24.09.2026: closeModal(), затем асинхронный переход с await внутри)
   раскладываются на ДВЕ разные
   задачи — и observer честно срабатывал дважды: сначала видел глубину 0 и
   звал history.back(), потом видел глубину 1 и звал pushState(). Между этими
   двумя вызовами болтался ещё не выполненный traversal от back(), и итоговый
   индекс в истории переставал соответствовать нашему счётчику: следующий ✕
   уводил на одну запись дальше, чем нужно, то есть ВОН ИЗ КАРТЫ.

   Отложив на кадр, мы видим такую замену как то, чем она и является: глубина
   была 1 и осталась 1, историю трогать вообще не нужно. */
let syncScheduled = false;
function scheduleSync() {
  if (syncScheduled) return;
  syncScheduled = true;
  requestAnimationFrame(() => { syncScheduled = false; sync(); });
}

// Слои открываются/закрываются из четырёх разных модулей (modal/system-view/
// phenom/stories) — вместо того, чтобы дёргать sync() из каждого из них,
// смотрим на сам DOM: один MutationObserver разом на все четыре оверлея.
// Несколько .observe() на ОДНОМ экземпляре батчатся в один вызов колбэка —
// поэтому "закрыли одно и тут же открыли другое за один синхронный клик"
// даёт один sync(), а не два, и если итоговая глубина не изменилась —
// история вообще не трогается.
const observer = new MutationObserver(scheduleSync);
['modalBackdrop', 'systemOverlay', 'phenomOverlay', 'storyOverlay', 'charOverlay', 'tourOverlay'].forEach(id => {
  observer.observe(document.getElementById(id), { attributes: true, attributeFilter: ['class'] });
});
