    print(f"\n  РіРѕС‚РѕРІРѕ: {grid}x{grid} С‚Р°Р№Р»РѕРІ РїРѕ {TILE}px = {out_px}px РїРѕ СЃС‚РѕСЂРѕРЅРµ")
    print(f"  С‚Р°Р№Р»С‹: {total/1024/1024:.2f} РњР‘, РїСЂРµРІСЊСЋ: {prev_size/1024:.0f} РљР‘")
    print(f"  РёС‚РѕРіРѕ: {(total+prev_size)/1024/1024:.2f} РњР‘ "
          f"(РіСЂСѓР·РёС‚СЃСЏ С‚РѕР»СЊРєРѕ РїСЂРё РІС…РѕРґРµ РІ В«Р“СЂР°С„РёРєСѓВ»)")


